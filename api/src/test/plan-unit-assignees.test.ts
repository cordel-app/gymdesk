// #2609 stage 3 — each unit of an Individual Product a Membership Plan includes is for one
// family member: one unit per beneficiary by default, changeable to the owner or a family
// member while the assignment is a Draft, refused once confirmed, outside the family, or on
// a shared Product.

import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { db } from '../infra/db';
import { TEST_AUTH_HEADER, cleanupTestGyms, createTestGym, createTestMembership, request } from './helpers';

let gymId: string;
let otherGymId: string;
let planId: number;
let insuranceId: number;
let familyBoxId: number;
let owner: number;
let kidA: number;
let kidB: number;
let stranger: number;
let seq = 0;
const uniq = () => `${Date.now()}-${(seq += 1)}-${Math.random().toString(36).slice(2, 6)}`;
const today = () => new Date().toISOString().slice(0, 10);

const as = (r: any, gym = gymId) => r.set('Authorization', TEST_AUTH_HEADER).set('x-gym-id', gym);

async function member(name: string): Promise<number> {
  const { insertId } = await db.query('INSERT INTO members (gym_id, name, email) VALUES (?, ?, ?)',
    [gymId, name, `pua-${uniq()}@test.com`]);
  return Number(insertId);
}

async function product(name: string, sharing: 'individual' | 'shared'): Promise<number> {
  const { insertId } = await db.query(
    `INSERT INTO products (gym_id, name, type, amount, currency, billing_frequency, status, enrollment_status, is_system, sharing_type, created_by)
     VALUES (?, ?, 'fee', 10, 'EUR', 'once', 'active', 'public', 0, ?, 'test')`, [gymId, name, sharing]);
  return Number(insertId);
}

/** A Draft for the owner covering both children, as the Assign Plan flow leaves it. */
async function familyDraft(): Promise<number> {
  const res = await as(request.post('/user-memberships')).send({ member_id: owner, membership_plan_id: planId, starts_at: today() });
  expect(res.status).toBe(201);
  const umId = Number(res.body.id);
  for (const kid of [kidA, kidB]) {
    const add = await as(request.post(`/user-memberships/${umId}/members`)).send({ member_id: kid });
    expect(add.status).toBe(201);
  }
  return umId;
}

async function oneoffLines(umId: number) {
  const res = await as(request.get(`/user-memberships/${umId}/oneoff-benefits`));
  expect(res.status).toBe(200);
  return res.body as any[];
}

const ids = (line: any) => line.unit_assignees?.map((m: any) => m.member_id) ?? null;
/** #2657 stage 3: an Individual Product held per member is several lines; its units in line order. */
const productUnits = (lines: any[], productId: number) =>
  lines.filter((l) => l.product_id === productId).flatMap((l) => ids(l) ?? []);

beforeAll(async () => {
  gymId = await createTestGym('Plan unit assignees gym');
  otherGymId = await createTestGym('Plan unit assignees other gym');
  await createTestMembership(gymId, 'admin');
  await createTestMembership(otherGymId, 'admin');
  owner = await member('Ana Owner');
  kidA = await member('Bea Kid');
  kidB = await member('Carla Kid');
  stranger = await member('Dani Stranger');
  await as(request.post(`/members/${owner}/family`)).send({});
  for (const kid of [kidA, kidB]) {
    expect((await as(request.post(`/members/${owner}/family/members`)).send({ member_id: kid })).status).toBeLessThan(300);
  }
  insuranceId = await product(`Insurance ${uniq()}`, 'individual');
  familyBoxId = await product(`Family box ${uniq()}`, 'shared');
  const plan = await db.query(
    `INSERT INTO membership_plans (gym_id, name, lifecycle_status, enrollment_status, member_limit)
     VALUES (?, ?, 'active', 'public', 'family')`, [gymId, `Family plan ${uniq()}`]);
  planId = Number(plan.insertId);
  await db.query(
    `INSERT INTO membership_plan_oneoff (gym_id, membership_plan_id, product_id, quantity, mandatory)
     VALUES (?, ?, ?, 3, 1), (?, ?, ?, 1, 1)`, [gymId, planId, insuranceId, gymId, planId, familyBoxId]);
});

afterAll(async () => {
  await cleanupTestGyms();
  await db.end();
});

describe('Individual Products generated by a plan', () => {
  it('gives one unit to each beneficiary by default and none to a shared Product', async () => {
    const umId = await familyDraft();
    const lines = await oneoffLines(umId);
    const insurance = lines.find((l) => l.product_id === insuranceId);
    const box = lines.find((l) => l.product_id === familyBoxId);
    expect(ids(insurance)).toEqual([owner, kidA, kidB]);
    expect(insurance.unit_assignees.map((m: any) => m.name)).toEqual(['Ana Owner', 'Bea Kid', 'Carla Kid']);
    expect(box.unit_assignees).toBeNull();

    const opts = await as(request.get(`/user-memberships/${umId}/benefit-assignees`));
    expect(opts.status).toBe(200);
    expect(opts.body.editable).toBe(true);
    expect(opts.body.eligible.map((m: any) => m.member_id).sort()).toEqual([owner, kidA, kidB].sort());
  });

  it('lets staff redistribute the units before confirming, several to one member included', async () => {
    const umId = await familyDraft();
    const res = await as(request.put(`/user-memberships/${umId}/benefit-assignees`))
      .send({ section: 'oneoff', product_id: insuranceId, assignees: [kidA, kidA, owner] });
    expect(res.status).toBe(200);
    expect(productUnits(res.body, insuranceId)).toEqual([kidA, kidA, owner]);
    // #2657 stage 3: stored as one line per member, each with its own units.
    const lines = (await oneoffLines(umId)).filter((l) => l.product_id === insuranceId);
    expect(lines.map((l) => [l.assigned_member_id, l.quantity])).toEqual([[kidA, 2], [owner, 1]]);

    // A member's line grows on its own; the other member's units stay.
    const grow = await as(request.put(`/user-memberships/${umId}/oneoff-benefits`))
      .send({ items: [
        { product_id: insuranceId, assigned_member_id: kidA, quantity: 2 },
        { product_id: insuranceId, assigned_member_id: owner, quantity: 2 },
        { product_id: familyBoxId, quantity: 1 },
      ] });
    expect(grow.status).toBe(200);
    expect(productUnits(await oneoffLines(umId), insuranceId)).toEqual([kidA, kidA, owner, owner]);
  });

  it('refuses an outsider, a wrong number of units, a shared Product and an unknown line', async () => {
    const umId = await familyDraft();
    const put = (body: object) => as(request.put(`/user-memberships/${umId}/benefit-assignees`)).send(body);
    expect((await put({ section: 'oneoff', product_id: insuranceId, assignees: [owner, kidA, stranger] })).status).toBe(400);
    expect((await put({ section: 'oneoff', product_id: insuranceId, assignees: [owner, kidA] })).status).toBe(400);
    expect((await put({ section: 'oneoff', product_id: insuranceId, assignees: [owner, 'x', kidA] })).status).toBe(400);
    expect((await put({ section: 'oneoff', product_id: familyBoxId, assignees: [kidA] })).status).toBe(400);
    expect((await put({ section: 'session', product_id: insuranceId, assignees: [owner, kidA, kidB] })).status).toBe(400);
    expect((await put({ section: 'nope', product_id: insuranceId, assignees: [owner, kidA, kidB] })).status).toBe(400);
    expect(productUnits(await oneoffLines(umId), insuranceId)).toEqual([owner, kidA, kidB]);
  });

  it('keeps the distribution once confirmed and refuses changing it afterwards', async () => {
    const umId = await familyDraft();
    expect((await as(request.put(`/user-memberships/${umId}/benefit-assignees`))
      .send({ section: 'oneoff', product_id: insuranceId, assignees: [kidB, kidB, kidB] })).status).toBe(200);
    const act = await as(request.post(`/user-memberships/${umId}/activate`)).send({ confirm: true });
    expect(act.status).toBeLessThan(300);
    expect(ids((await oneoffLines(umId)).find((l) => l.product_id === insuranceId))).toEqual([kidB, kidB, kidB]);
    const late = await as(request.put(`/user-memberships/${umId}/benefit-assignees`))
      .send({ section: 'oneoff', product_id: insuranceId, assignees: [owner, owner, owner] });
    expect(late.status).toBe(409);
    expect((await as(request.get(`/user-memberships/${umId}/benefit-assignees`))).body.editable).toBe(false);
  });

  it('is invisible to another gym', async () => {
    const umId = await familyDraft();
    expect((await as(request.get(`/user-memberships/${umId}/benefit-assignees`), otherGymId)).status).toBe(404);
    expect((await as(request.put(`/user-memberships/${umId}/benefit-assignees`), otherGymId)
      .send({ section: 'oneoff', product_id: insuranceId, assignees: [owner, owner, owner] })).status).toBe(404);
  });
});
